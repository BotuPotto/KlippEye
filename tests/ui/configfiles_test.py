FAILS = []
def ok(name, cond, extra=""):
    if not cond: FAILS.append(name)
    print(("PASS " if cond else "FAIL ") + name + ((" :: " + str(extra)) if extra != "" else ""))
def card(P): return P.pg.locator(".oui-card:has(.oui-card-title:text-is('File di configurazione'))").first
def names(P): return card(P).locator(".cfg-row__name").all_inner_texts()
def row(P, name): return card(P).locator(".cfg-row", has=P.pg.locator(".cfg-row__name", has_text=re.compile("^" + re.escape(name) + "$"))).first
def log(prefix=""): return [g for g in mock.gcode() if re.match(r"^(MKDIR|RMDIR|MOVE|DELETE_CFG|UPLOAD)", g) and g.startswith(prefix)]
def toast(P): return " | ".join(P.pg.locator(".toast").all_inner_texts())
def open_menu(P, name):
    row(P, name).locator(".cfg-row__more").click(); P.pg.wait_for_selector(".sheet-overlay--actions"); P.pg.wait_for_timeout(520)  # the early-click guard
def pick(P, title):
    P.pg.locator(".sheet-overlay--actions .file-action", has_text=title).click(); P.pg.wait_for_timeout(300)
def new_menu(P, entry):
    card(P).locator("button:has-text('Nuovo')").click(); P.pg.wait_for_selector(".oui-menu")
    P.pg.locator(".oui-menu__item", has_text=entry).click(); P.pg.wait_for_timeout(350)
def name_dialog(P): return P.pg.locator(".modal-card")
def type_name(P, text):
    i = name_dialog(P).locator("input"); i.fill(text); P.pg.wait_for_timeout(80)
def submit(P):
    name_dialog(P).locator("button.oui-btn--primary").click(); P.pg.wait_for_timeout(900)
def wait_names(P, expected, ms=3000):
    try: P.pg.wait_for_function("(e) => JSON.stringify([...document.querySelectorAll('.cfg-row__name')].map(x => x.innerText)) === JSON.stringify(e)", arg=expected, timeout=ms)
    except Exception: pass
    return names(P)
