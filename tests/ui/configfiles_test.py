def fresh(w=390, h=844, wait=1500, init=None, **state):
    mock.reset()
    if state: mock.set(**state)
    P = Page(b, mock, w, h)
    P.ctx.add_init_script(FONT)
    if init: P.ctx.add_init_script(init)
